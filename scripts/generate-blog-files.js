#!/usr/bin/env node
/**
 * Reads content/blog/*.md, copies to src/assets/blog/, writes index + RSS + route helpers.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CONTENT_DIR = path.join(ROOT, 'content', 'blog');
const ASSETS_DIR = path.join(ROOT, 'src', 'assets', 'blog');
const GENERATED_TS = path.join(ROOT, 'src', 'app', 'blog', 'blog-posts.generated.ts');
const RSS_FILE = path.join(ROOT, 'static', 'rss.xml');
const SITE_ORIGIN = 'https://sebastienbarbier.com';

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!match) {
    return { meta: {}, body: raw };
  }
  const meta = {};
  for (const line of match[1].split('\n')) {
    const m = line.match(/^(\w+):\s*(.+)$/);
    if (m) {
      const key = m[1];
      let value = m[2].replace(/^['"]|['"]$/g, '').trim();
      if (key === 'draft') {
        meta.draft = /^(true|yes|1)$/i.test(value);
      } else {
        meta[key] = value;
      }
    }
  }
  return { meta, body: match[2] };
}

function loadPosts() {
  if (!fs.existsSync(CONTENT_DIR)) {
    return [];
  }
  const files = fs
    .readdirSync(CONTENT_DIR)
    .filter((f) => f.endsWith('.md'))
    .sort();

  return files.map((file) => {
    const raw = fs.readFileSync(path.join(CONTENT_DIR, file), 'utf8');
    const { meta, body } = parseFrontmatter(raw);
    const slug = meta.slug || file.replace(/\.md$/, '');
    return {
      slug,
      title: meta.title || slug,
      ogTitle: meta.ogTitle || meta.title || slug,
      description: meta.description || '',
      date: meta.date || '',
      draft: Boolean(meta.draft),
      fileName: `${slug}.md`,
      bodyLength: body.trim().length,
      og: {
        eyebrow: meta.ogEyebrow || 'Blog',
        description: meta.ogDescription || meta.description || '',
      },
    };
  });
}

function writeAssets(posts) {
  fs.mkdirSync(ASSETS_DIR, { recursive: true });
  for (const file of fs.readdirSync(CONTENT_DIR).filter((f) => f.endsWith('.md'))) {
    const raw = fs.readFileSync(path.join(CONTENT_DIR, file), 'utf8');
    const { meta, body } = parseFrontmatter(raw);
    const slug = meta.slug || file.replace(/\.md$/, '');
    fs.writeFileSync(path.join(ASSETS_DIR, `${slug}.md`), body.trim() + '\n');
  }
}

function writeGeneratedTs(posts) {
  fs.mkdirSync(path.dirname(GENERATED_TS), { recursive: true });
  const slim = posts.map((p) => ({
    slug: p.slug,
    title: p.title,
    ogTitle: p.ogTitle,
    description: p.description,
    date: p.date,
    draft: p.draft,
    og: p.og,
  }));
  const bodies = {};
  for (const file of fs.readdirSync(CONTENT_DIR).filter((f) => f.endsWith('.md'))) {
    const raw = fs.readFileSync(path.join(CONTENT_DIR, file), 'utf8');
    const { meta, body } = parseFrontmatter(raw);
    const slug = meta.slug || file.replace(/\.md$/, '');
    bodies[slug] = body.trim();
  }
  const body = `/** Generated by scripts/generate-blog-files.js. Do not edit. */
export type BlogPostMeta = {
  slug: string;
  title: string;
  ogTitle?: string;
  description: string;
  date: string;
  draft?: boolean;
  og: { eyebrow: string; description: string };
};

export const BLOG_POSTS: BlogPostMeta[] = ${JSON.stringify(slim, null, 2)} as const;

export const BLOG_POST_BODIES: Record<string, string> = ${JSON.stringify(bodies, null, 2)};

export function blogPostBySlug(slug: string): BlogPostMeta | undefined {
  return BLOG_POSTS.find((p) => p.slug === slug);
}

export function blogPostBodyBySlug(slug: string): string {
  return BLOG_POST_BODIES[slug] ?? '';
}
`;
  fs.writeFileSync(GENERATED_TS, body);
}

function publishedPosts(posts) {
  return posts.filter((p) => !p.draft);
}

function writeRss(posts) {
  const sorted = [...publishedPosts(posts)].sort((a, b) => (a.date < b.date ? 1 : -1));
  const items = sorted
    .map((post) => {
      const link = `${SITE_ORIGIN}/blog/${post.slug}`;
      return `    <item>
      <title>${escapeXml(post.title)}</title>
      <link>${link}</link>
      <guid isPermaLink="true">${link}</guid>
      <description>${escapeXml(post.description)}</description>
      <pubDate>${pubDate(post.date)}</pubDate>
    </item>`;
    })
    .join('\n');

  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0">
  <channel>
    <title>Sébastien Barbier</title>
    <link>${SITE_ORIGIN}/blog</link>
    <description>Writing by Sébastien Barbier, staff software engineer in Zürich.</description>
    <language>en</language>
${items}
  </channel>
</rss>
`;
  fs.writeFileSync(RSS_FILE, xml);
}

function escapeXml(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function pubDate(isoDate) {
  if (!isoDate) return new Date().toUTCString();
  return new Date(isoDate + 'T12:00:00Z').toUTCString();
}

function writeOgPages(posts) {
  const ogPages = posts.map((post) => ({
    slug: `blog-${post.slug}`,
    path: `/blog/${post.slug}`,
    state: `blog-${post.slug}`,
    title: post.ogTitle || post.title,
    eyebrow: post.og.eyebrow,
    description: post.og.description || post.description,
    draft: post.draft,
  }));
  fs.writeFileSync(
    path.join(ROOT, 'static', 'blog-og-pages.json'),
    JSON.stringify(ogPages, null, 2) + '\n',
  );
}

function main() {
  const posts = loadPosts();
  writeAssets(posts);
  writeGeneratedTs(posts);
  writeRss(posts);
  writeOgPages(posts);
  console.log(`Blog: ${posts.length} post(s), wrote assets, ${path.relative(ROOT, GENERATED_TS)}, rss.xml`);
}

main();
